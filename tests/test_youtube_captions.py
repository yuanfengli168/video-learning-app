def test_pick_language_prefers_user_locked():
    """When admin locked a language and it's available, that wins."""
    chosen = _pick_language_priority(
        user_locked="zh-Hans",
        available_languages=["en", "zh-Hans", "ja"],
    )
    assert chosen == "zh-Hans"


def test_pick_language_skips_locked_if_unavailable():
    """If admin locked a language but YouTube doesn't have it, fall
    through to the next priority (NOT an error — yt-dlp might still
    find it as auto-generated)."""
    chosen = _pick_language_priority(
        user_locked="fr",  # not in available
        available_languages=["en", "ja"],
    )
    # Falls through to the first available
    assert chosen == "en"


def test_pick_language_prefers_first_available_when_no_lock():
    """No user lock, English is first in available → English wins (was
    the previous behavior; preserved because preferred_languages defaults
    to English so both rules agree)."""
    chosen = _pick_language_priority(
        user_locked=None,
        available_languages=["en", "zh-Hans", "ja"],
    )
    assert chosen == "en"


def test_pick_language_prefers_english_even_if_list_starts_with_other():
    """Regression for Day-13 catalog-curation bug.

    The Rick Astley YouTube submission had
        caption_languages = ["de-DE", "en", "ja", "es-419", "en", "pt-BR"]
    The old picker returned available_languages[0] = "de-DE", so the
    transcript was German. After the fix, preferred_languages=("en",
    "en-US", "en-GB") is checked BEFORE the first-available fallback,
    so English wins even when YouTube returns non-English first.
    """
    chosen = _pick_language_priority(
        user_locked=None,
        available_languages=["de-DE", "en", "ja", "es-419", "en", "pt-BR"],
    )
    assert chosen == "en"


def test_pick_language_prefers_english_variant_as_fallback():
    """No lock, no available list (yt-dlp will figure it out):
    fall back to a preference list, defaulting to English variants."""
    chosen = _pick_language_priority(
        user_locked=None,
        available_languages=[],  # unknown — we'll let yt-dlp pick
    )
    # No available languages means chosen=None; yt-dlp will pick.
    # The function only kicks in the preferred_languages list when
    # available_languages is non-empty AND doesn't contain the user's
    # lock. With empty available list, return None.
    assert chosen is None


def test_pick_language_falls_back_to_preferred_when_available_empty():
    """Edge case: user locked 'fr', not available, no available list.
    Should return None (yt-dlp will pick whatever it has)."""
    chosen = _pick_language_priority(
        user_locked="fr",
        available_languages=[],
    )
    assert chosen is None


def test_pick_language_returns_none_for_unknown_combo():
    """Defensive: malformed inputs → None (let yt-dlp try)."""
    chosen = _pick_language_priority(
        user_locked=None,
        available_languages=None,
    )
    assert chosen is None


