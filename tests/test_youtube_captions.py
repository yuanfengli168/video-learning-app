def test_parse_real_youtube_auto_caption_format():
    """Snapshot of a real YouTube auto-generated VTT file.
    Includes NOTE blocks, multiple cues, and inline tags.
    """
    vtt = """WEBVTT
Kind: captions
Language: en

NOTE
Confidence: 0.9453125

NOTE
Confidence: 0.9453
Line: 0
Word: 0
Op: 0

00:00:00.500 --> 00:00:02.500 align:start position:0%
    <c>hello</c><c> and</c><c> welcome</c>

00:00:02.500 --> 00:00:05.000 align:start position:0%
<c>to</c><c> the</c><c> channel</c>
"""
    segments = parse_vtt_text(vtt)
    # Two real cues; the NOTE blocks are skipped
    assert len(segments) == 2
    assert "hello" in segments[0]["text"]
    assert "welcome" in segments[0]["text"]
    assert "channel" in segments[1]["text"]